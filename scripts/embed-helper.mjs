import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const sourceDirs = [
  path.join(rootDir, "native", "macos", "Sources", "PaseoComputerUseCore"),
  path.join(rootDir, "native", "macos", "Sources", "PaseoComputerUseHelper"),
];

/** @type {Record<string, string>} */
const sources = {};
const hash = createHash("sha256");

for (const dir of sourceDirs) {
  const entries = readdirSync(dir)
    .filter((file) => file.endsWith(".swift"))
    .sort();
  for (const file of entries) {
    const fullPath = path.join(dir, file);
    const content = readFileSync(fullPath, "utf8");
    sources[file] = content;
    hash.update(`${file}\0${content}\0`);
  }
}

const sourceHash = hash.digest("hex").slice(0, 16);
const outDir = path.join(rootDir, "server", "computer-use-mcp", "helper");
mkdirSync(outDir, { recursive: true });

const outFile = path.join(outDir, "sources.generated.ts");
const lines = [
  "// AUTO-GENERATED by scripts/embed-helper.mjs — DO NOT EDIT.",
  "",
  `export const HELPER_SOURCE_HASH = ${JSON.stringify(sourceHash)};`,
  "",
  `export const HELPER_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};`,
  "",
];

writeFileSync(outFile, lines.join("\n"), "utf8");
console.log(
  `Embedded ${Object.keys(sources).length} Swift source files (hash: ${sourceHash}) -> ${path.relative(rootDir, outFile)}`,
);
